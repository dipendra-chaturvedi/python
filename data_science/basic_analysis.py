import statistics

salaries = [50000, 60000, 70000]

average_salary = statistics.mean(salaries)

print("Average Salary:", average_salary)

data = [10, 20, 20, 30, 40]

print(statistics.mean(data))
print(statistics.median(data))
print(statistics.mode(data))


